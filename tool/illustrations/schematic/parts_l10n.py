#!/usr/bin/env python3
"""Sxema qismlari matnlari: parts_src.py -> JSON asset, ARB (uz/ru/en), Dart
id->matn jadvali, manbalar hujjati va PNG kelib chiqishi (sha256) jadvali.

    python3 tool/illustrations/schematic/parts_l10n.py
    flutter gen-l10n

Yozadi:
  assets/instruments/schematic_parts.json      — kalit -> qismlar (n, id), prinsip/natija id
  lib/l10n/app_{uz,ru,en}.arb                  — FAQAT `schemParts*` kalitlari (labSchem*
                                                 blokidan keyin; boshqa qatorlar o'zgarmaydi)
  lib/features/instruments/schematic_parts_l10n.dart — id -> AppLocalizations getter
  docs/SCHEMATIC_PARTS_SOURCES.md              — qism -> manba (catalog.json) yoki
                                                 STANDARD_TEXTBOOK (NEEDS_EXPERT)
  docs/SCHEMATICS_PROVENANCE.md                — “Fayllar (sha256)” jadvali (32 chizma)
"""
import hashlib
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
from parts_src import PARTS, TB  # noqa: E402
from gen import SCENES  # noqa: E402

PREFIX = "schemParts"
LANGS = ("uz", "ru", "en")
DATE = "2026-10-25"

# Panel sarlavhalari (SchematicPartsPanel).
UI = {
    "PanelTitle": ("Qismlari va ishlash prinsipi", "Узлы и принцип работы", "Parts and how it works"),
    "PanelHint": ("Rasmdagi raqamlar bo'yicha qismlar, prinsip va natija",
                  "Узлы по номерам на рисунке, принцип и результат",
                  "Numbered parts, working principle and result"),
    "PartsTitle": ("Asosiy qismlar", "Основные узлы", "Main parts"),
    "PrincipleTitle": ("Ishlash prinsipi", "Принцип работы", "Working principle"),
    "ResultTitle": ("Natija", "Результат", "Result"),
    "ClassNote": ("Qismlar apparat sinfi uchun umumiy, tamoyil darajasida ko'rsatilgan; aniq modelda joylashuvi va tuzilishi boshqacha bo'lishi mumkin.",
                  "Узлы показаны для класса приборов на уровне принципа; в конкретной модели расположение и устройство могут отличаться.",
                  "Parts are shown for the instrument class at principle level; their layout and design in a specific model may differ."),
}

# Model kartasidagi 7 ta tur chizmasi (InstrumentSchematic) — qolgani LabSchematic.
MODEL_KEYS = ["chemistry", "photometer", "hematology5", "hematology3", "immunoassay", "urine_strip", "urine_system"]

_OG = re.compile(r"(?<=[oOgG])'(?=[A-Za-z])")
_TUTUQ = re.compile(r"(?<=[A-Za-z])'(?=[A-Za-z])")


def uz_norm(s):
    return _TUTUQ.sub("’", _OG.sub("‘", s))


def camel(s):
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"_", s))


def stem(key):
    return PREFIX + camel(key)


def build():
    """(arb: {lang: [(key, value)]}, asset dict, docs rows)."""
    arb = {lang: [] for lang in LANGS}
    for k, vals in UI.items():
        for lang, v in zip(LANGS, vals):
            arb[lang].append((PREFIX + k, v))
    schem = {}
    for key, entry in PARTS.items():
        base = stem(key)
        parts = []
        for n, p in enumerate(entry["parts"], 1):
            pid = base + camel(p["slug"])
            parts.append({"n": n, "id": pid})
            for lang in LANGS:
                name, fn = p[lang]
                arb[lang].append((pid + "Name", name))
                arb[lang].append((pid + "Fn", fn))
        for what in ("principle", "result"):
            for lang in LANGS:
                arb[lang].append((base + what.capitalize(), entry[what][lang]))
        schem[key] = {"parts": parts, "principle_id": base + "Principle", "result_id": base + "Result"}
    arb["uz"] = [(k, uz_norm(v)) for k, v in arb["uz"]]
    asset = {
        "schema_version": 1,
        "updated": DATE,
        "note": "Generated by tool/illustrations/schematic/parts_l10n.py from parts_src.py. "
                "Texts live in lib/l10n/app_*.arb; ids are ARB key stems (<id>Name, <id>Fn).",
        "schematics": schem,
    }
    return arb, asset


def write_arb(lang, entries):
    """`schemParts*` blokini `labSchemAnalyticalBalance` qatoridan keyin yozadi:
    mavjud qatorlar o'zgarmaydi (fayl oxiriga boshqa kalit qo'shayotganlar bilan
    to'qnashuv bo'lmaydi); qayta ishga tushirilsa — faqat shu blok yangilanadi."""
    path = ROOT / f"lib/l10n/app_{lang}.arb"
    raw = path.read_text(encoding="utf-8")
    lines = raw.split("\n")
    mine = re.compile(r'^\s*"@?' + PREFIX + r'[A-Za-z0-9]*":')
    kept = [ln for ln in lines if not mine.match(ln)]
    anchor = [i for i, ln in enumerate(kept) if ln.startswith('  "labSchemAnalyticalBalance": ')]
    assert len(anchor) == 1 and kept[anchor[0]].endswith(","), (lang, "anchor")
    block = [f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}," for k, v in entries]
    out = "\n".join(kept[: anchor[0] + 1] + block + kept[anchor[0] + 1:])
    data = json.loads(out)
    before = json.loads(raw)
    for k, v in before.items():
        if not k.lstrip("@").startswith(PREFIX):
            assert data[k] == v, (lang, k)
    assert list(k for k in data if not k.startswith(PREFIX)) == list(k for k in before if not k.startswith(PREFIX))
    path.write_text(out, encoding="utf-8")


def write_dart(arb_en):
    ids = [k for k, _ in arb_en if not any(k == PREFIX + u for u in UI)]
    def case(k):  # dart format bilan bir xil (80 belgi)
        one = f"  '{k}' => l.{k},"
        return one if len(one) <= 80 else f"  '{k}' =>\n    l.{k},"

    cases = "\n".join(case(k) for k in ids)
    idset = "\n".join(f"  '{k}'," for k in ids)
    src = f"""// GENERATED by tool/illustrations/schematic/parts_l10n.py — qo'lda tahrirlamang.
// Manba: tool/illustrations/schematic/parts_src.py (matnlar ARB da).
import '../../l10n/gen/app_localizations.dart';

/// `assets/instruments/schematic_parts.json` dagi matn id'si (`<id>Name`,
/// `<id>Fn`, `principle_id`, `result_id`) -> joriy tildagi ARB matni.
/// Noma'lum id — null (qorovul testi ushlaydi).
String? schematicPartsText(AppLocalizations l, String id) => switch (id) {{
{cases}
  _ => null,
}};

/// Jadvaldagi barcha id'lar (qorovul testi uchun).
const schematicPartsTextIds = <String>{{
{idset}
}};
"""
    (ROOT / "lib/features/instruments/schematic_parts_l10n.dart").write_text(src, encoding="utf-8")


def write_docs(catalog):
    src = {s["id"]: s for s in catalog["sources"]}
    cards = {}
    for c in catalog["lab_cards"]:
        if c.get("schematic"):
            cards.setdefault(c["schematic"], []).append(c["id"])
    models = {}
    defaults = {"chemistry": "chemistry", "hematology": "hematology5", "immunoassay": "immunoassay",
                "urinalysis": "urine_strip"}
    for m in catalog["models"]:
        models.setdefault(m.get("schematic") or defaults[m["category"]], []).append(m["id"])

    def cite(ids):
        out = []
        for i in ids:
            if i == TB:
                out.append("`STANDARD_TEXTBOOK (NEEDS_EXPERT)`")
            else:
                assert i in src, i
                out.append(f"`{i}` <{src[i]['url']}>")
        return "; ".join(out)

    lines = [
        f"# Sxema qismlari — manbalar ({DATE})",
        "",
        "Har bir apparat sinfi chizmasidagi raqamli belgi (1..n) → qism nomi va vazifasi,",
        "ishlash prinsipi va natija (ilovada “Qismlari va ishlash prinsipi” paneli,",
        "`SchematicPartsPanel`). Matnlar — `lib/l10n/app_{uz,ru,en}.arb` dagi `schemParts*`",
        "kalitlari; tuzilma — `assets/instruments/schematic_parts.json`; yagona manba —",
        "`tool/illustrations/schematic/parts_src.py` (generator `parts_l10n.py`).",
        "",
        "Qoida: faqat darslik darajasidagi umumiy apparat anatomiyasi va kartaning o‘z",
        "manbali matniga (catalog.json `technology`, `principle`, `tasks`, `sources`) zid",
        "bo‘lmagan tamoyil. Aniq model xususiyati, ishlab chiqaruvchi dizayni, o‘ylab",
        "topilgan raqam va klinik tashxis yo‘q. Manba ustuni: catalog.json `sources[].id`",
        "(URL bilan) yoki `STANDARD_TEXTBOOK (NEEDS_EXPERT)` — darslik darajasidagi umumiy",
        "ma’lumot, mutaxassis tasdig‘ini kutadi.",
        "",
    ]
    total = needs = 0
    for key, entry in PARTS.items():
        kind = "model turi (InstrumentSchematic)" if key in MODEL_KEYS else "yo‘nalish kartasi sinfi (LabSchematic)"
        used = cards.get(key) or models.get(key) or []
        lines += [f"## `{key}` — {kind}", "",
                  "Kartalar: " + ", ".join(f"`{u}`" for u in used), "",
                  "| # | qism (en) | manba |", "|---|---|---|"]
        for n, p in enumerate(entry["parts"], 1):
            total += 1
            needs += TB in p["src"]
            lines.append(f"| {n} | {p['en'][0]} | {cite(p['src'])} |")
        lines.append(f"| P | Principle | {cite(entry['principle']['src'])} |")
        lines.append(f"| R | Result | {cite(entry['result']['src'])} |")
        lines.append("")
    lines.insert(15, f"Jami: {len(PARTS)} chizma, {total} qism; {needs} tasida (to‘liq yoki qisman) "
                     "`STANDARD_TEXTBOOK (NEEDS_EXPERT)`.")
    lines.insert(16, "")
    (ROOT / "docs/SCHEMATIC_PARTS_SOURCES.md").write_text("\n".join(lines), encoding="utf-8")


def write_provenance():
    path = ROOT / "docs/SCHEMATICS_PROVENANCE.md"
    text = path.read_text(encoding="utf-8")
    head, sep, _ = text.partition("## Fayllar (sha256)")
    assert sep, "provenance section missing"
    rows = ["## Fayllar (sha256)", "",
            f"Yaratilgan/yangilangan: {DATE} (raqamli qism belgilari qo‘shildi). Vosita:",
            "`tool/illustrations/schematic/gen.py` → `render.cjs --schematic --quant`.",
            "LabGuide’ning o‘z original ishi; ishlab chiqaruvchi dizayni yo‘q.", "",
            "| Fayl | Chizma | O‘lcham | Hajm | sha256 |", "|---|---|---|---|---|"]
    lab = [k for k in SCENES if k not in MODEL_KEYS]
    for key in list(SCENES):
        label = f"L{lab.index(key) + 1} `{key}`" if key in lab else f"M `{key}`"
        for suffix, dim in (("480", "480×320"), ("1200", "1200×800")):
            f = ROOT / f"assets/instruments/schematic/{key}_{suffix}.png"
            b = f.read_bytes()
            rows.append(f"| `{f.name}` | {label} | {dim} | {round(len(b) / 1024)} KB | "
                        f"`{hashlib.sha256(b).hexdigest()}` |")
    path.write_text(head + "\n".join(rows) + "\n", encoding="utf-8")


def main():
    catalog = json.loads((ROOT / "assets/instruments/catalog.json").read_text(encoding="utf-8"))
    ids = {s["id"] for s in catalog["sources"]}
    for key, entry in PARTS.items():
        for p in entry["parts"]:
            for s in p["src"]:
                assert s == TB or s in ids, (key, p["slug"], s)
            for lang in LANGS:
                assert len(p[lang]) == 2 and all(x.strip() for x in p[lang]), (key, p["slug"], lang)
        for what in ("principle", "result"):
            for s in entry[what]["src"]:
                assert s == TB or s in ids, (key, what, s)
    assert list(PARTS) == list(SCENES), "parts_src order must match gen.py SCENES"
    arb, asset = build()
    for lang in LANGS:
        write_arb(lang, arb[lang])
    (ROOT / "assets/instruments/schematic_parts.json").write_text(
        json.dumps(asset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_dart(arb["en"])
    write_docs(catalog)
    write_provenance()
    print("ok", len(PARTS), "schematics,", sum(len(e["parts"]) for e in PARTS.values()), "parts,",
          len(arb["en"]), "ARB keys per language")


if __name__ == "__main__":
    main()
