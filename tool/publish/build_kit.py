#!/usr/bin/env python3
"""Generate docs/video/publishing/<id>.md, SCHEDULE.md and SCHEDULE.csv from tool/publish/topics.py (stdlib).

    python3 tool/publish/build_kit.py            # write the files
    python3 tool/publish/build_kit.py --check    # lint only: exit 1 on any problem, write nothing

Only text is produced. Nothing is uploaded or published. A topic is marked READY only when it is listed in
video_studio/out/READY.txt or all of its rendered files are present.
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import chapters as chapters_mod  # noqa: E402
import kit  # noqa: E402
import schedule  # noqa: E402
from common import AUDIO_ROOT, DOCS_VIDEO, LANGS, OUT_ROOT, PUBLISH_DOCS  # noqa: E402
from topics import ALIASES, TOPICS  # noqa: E402


def ui_for(topic_id, docs_video=DOCS_VIDEO):
    out = {}
    for lang in LANGS:
        p = Path(docs_video) / topic_id / f"lines.{lang}.json"
        if p.is_file():
            out[lang] = json.loads(p.read_text(encoding="utf-8")).get("ui", {})
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="lint only, write nothing")
    ap.add_argument("--out", default=str(PUBLISH_DOCS), help="output directory (default docs/video/publishing)")
    ap.add_argument("--date", default=datetime.date.today().isoformat(), help="date label in SCHEDULE.md")
    args = ap.parse_args(argv)

    ready_ids = kit.read_ready_ids(OUT_ROOT)
    statuses, problems = {}, []
    for t in TOPICS:
        problems += kit.lint_topic(t)
        statuses[t["id"]] = kit.topic_status(t, OUT_ROOT, ready_ids)
    if problems:
        print("LINT PROBLEMS:", file=sys.stderr)
        for p in problems:
            print("  -", p, file=sys.stderr)
        return 1
    if args.check:
        print(f"lint OK for {len(TOPICS)} topics")
        return 0

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for t in TOPICS:
        ch = chapters_mod.compute(t, DOCS_VIDEO, AUDIO_ROOT)
        md = kit.render_md(t, ch, statuses[t["id"]], ui_for(t["id"]))
        (out / f"{t['id']}.md").write_text(md, encoding="utf-8")
        print(f"{t['id']:18s} {statuses[t['id']][0]:9s} chapters={'yes' if ch.get('chapters') else 'no '} "
              f"copy_verified={t['verified']}")
    for alias, canon in ALIASES.items():
        (out / f"{alias}.md").write_text(
            f"# Publishing kit — `{alias}`\n\n<!-- GENERATED by tool/publish/build_kit.py -->\n\n"
            f"This topic is called `{canon}` in the video studio (`docs/video/{canon}/`, "
            f"`video_studio/out/{canon}/`). Its kit is **[{canon}.md]({canon}.md)**. "
            f"`{alias}` is accepted as an alias by `tool/publish/package.py` and `READY.txt`.\n",
            encoding="utf-8")
    (out / "SCHEDULE.md").write_text(schedule.render_md(statuses, args.date), encoding="utf-8")
    (out / "SCHEDULE.csv").write_text(schedule.render_csv(statuses), encoding="utf-8")
    print(f"wrote {len(TOPICS)} kits + SCHEDULE.md + SCHEDULE.csv to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
