#!/usr/bin/env node
// Generates the reviewable documents of a video from the SAME sources the
// renderer uses (storyboard, language packs, timing, math):
//   docs/video/<id>/SCRIPT.md         narration (en) + subtitles (ru, uz) per scene, with time windows
//   docs/video/<id>/MATH_APPENDIX.md  data, least-squares sums, R², residuals, control read-off
//   docs/video/<id>/OUTPUTS.md        ffprobe facts + sha256 of out/<id>/** (after a render)
//   npm run docs -- --id calibration
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {LANGS, effectiveTiming, parseArgs, studio, videoData} from './lib.mjs';
import {buildCues} from '../src/lib/subtitles.js';
import {normalizeTiming} from '../src/lib/timing.js';

const args = parseArgs(process.argv.slice(2));
const id = args.id ?? 'calibration';
const {dir, storyboard, packs, math, lines} = videoData(id);
const {timing, layout, voiced} = effectiveTiming(id);
const t = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, '0')}`;
const esc = (s) => String(s).replace(/\|/g, '\\|');

// ---------------------------------------------------------------- SCRIPT
{
  const byId = new Map(normalizeTiming(timing).map((l) => [l.id, l]));
  let md = `# ${storyboard.title.en} — script (EN narration · RU/UZ subtitles)\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs from storyboard.json + lines.*.json + timing — do not edit by hand -->\n\n`;
  md += `Status: **EXPERT_REVIEW_PENDING** (science and translations not reviewed). Owner decision 2026-10-25: every edition uses the **English** narration; Russian and Uzbek editions differ only in subtitles and on-screen text.\n\n`;
  md += `Timing source: ${voiced ? `voice manifest \`video_studio/public/audio/en/${id}.timing.json\` (${timing.source}; ${timing.voice ?? ''})` : 'placeholder estimate (no voice)'} · total ${layout.totalSec.toFixed(2)} s.\n\n`;
  md += `| Scene | Layer | Line | Window (s) | EN (spoken) | RU (subtitle) | UZ (subtitle) |\n|---|---|---|---|---|---|---|\n`;
  for (const sc of layout.scenes) {
    sc.lines.forEach((lid, i) => {
      const l = byId.get(lid);
      md += `| ${i === 0 ? `**${sc.index + 1}. ${sc.id}** (${t(sc.startSec)}–${t(sc.endSec)})` : ''} | ${i === 0 ? sc.layer : ''} | ${lid} | ${l.start.toFixed(2)}–${l.end.toFixed(2)} | ${esc(lines.en[lid])} | ${esc(lines.ru[lid])} | ${esc(lines.uz[lid])} |\n`;
    });
  }
  const spoken = packs.en.spoken ?? {};
  md += `\n## TTS respellings (pronunciation only, same words)\n\n| Line | Sent to the synthesiser |\n|---|---|\n`;
  for (const [k, v] of Object.entries(spoken)) if (!k.startsWith('_')) md += `| ${k} | ${esc(v)} |\n`;
  md += `\n## Subtitle cues per language\n\n| Lang | Cues | Max chars / cue |\n|---|---|---|\n`;
  for (const lang of LANGS) {
    const cues = buildCues(normalizeTiming(timing), lines[lang]);
    md += `| ${lang} | ${cues.length} | ${Math.max(...cues.map((c) => [...c.text].length))} |\n`;
  }
  md += `\n## On-screen text (per language)\n\n| Key | EN | RU | UZ |\n|---|---|---|---|\n`;
  for (const k of Object.keys(packs.en.ui)) md += `| \`${k}\` | ${esc(packs.en.ui[k])} | ${esc(packs.ru.ui[k] ?? '—')} | ${esc(packs.uz.ui[k] ?? '—')} |\n`;
  fs.writeFileSync(path.join(dir, 'SCRIPT.md'), md);
}

// ----------------------------------------------------------------- MATH
if (id === 'leukocyte') {
  const {leukocyteAppendix} = await import('./appendix_leukocyte.mjs');
  fs.writeFileSync(path.join(dir, 'MATH_APPENDIX.md'), leukocyteAppendix({dir, storyboard, math, lines, studio}));
} else {
  const f = math.fit;
  const r = (v, d = 6) => (Math.abs(v) < 1e-12 ? '0' : v.toFixed(d));
  let md = `# ${storyboard.title.en} — math appendix\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs (same code as the video: video_studio/src/lib/regression.js) -->\n\n`;
  md += `**Illustrative data — not a patient result, not a real method.** Generic photometric example: absorbance A (dimensionless) against concentration c in arbitrary units (a.u.). Values are invented for teaching; they are defined once in \`storyboard.json → data\` and every number on screen is computed from them in code.\n\n`;
  md += `## 1. Data\n\n| Calibrator | c (a.u.) | A measured | A fitted | Residual (A − fitted) |\n|---|---|---|---|---|\n`;
  for (const c of math.calibrators) md += `| ${c.id} | ${c.conc} | ${c.abs.toFixed(3)} | ${r(c.fitted)} | ${r(c.residual)} |\n`;
  md += `\n## 2. Ordinary least squares (y = b₀ + b₁·x)\n\n`;
  md += `| Quantity | Formula | Value |\n|---|---|---|\n`;
  md += `| n | | ${f.n} |\n| x̄ | Σx / n | ${r(f.meanX)} |\n| ȳ | Σy / n | ${r(f.meanY)} |\n`;
  md += `| Sxx | Σ(x − x̄)² | ${r(f.sxx)} |\n| Sxy | Σ(x − x̄)(y − ȳ) | ${r(f.sxy)} |\n| Syy = SS_tot | Σ(y − ȳ)² | ${r(f.syy, 8)} |\n`;
  md += `| slope b₁ | Sxy / Sxx | ${r(f.slope, 8)} |\n| intercept b₀ | ȳ − b₁·x̄ | ${r(f.intercept, 8)} |\n`;
  md += `| SS_res | Σ(y − ŷ)² | ${r(f.ssRes, 10)} |\n| R² | 1 − SS_res / SS_tot | ${r(f.r2, 8)} |\n| s(y\\|x) | √(SS_res / (n − 2)) | ${r(f.sYX, 6)} |\n`;
  md += `\nShown on screen (rounded): slope ${f.slope.toFixed(4)}, intercept ${f.intercept.toFixed(4)}, R² ${f.r2.toFixed(4)}; residual signs ${math.signs.join(' ')} (max |residual| ${math.maxAbsResidual.toFixed(4)}).\n`;
  md += `\n## 3. Controls read off the curve (inverse prediction ĉ = (A − b₀) / b₁)\n\n| Control | Target c (a.u.) | A measured | ĉ (a.u.) | ĉ / target |\n|---|---|---|---|---|\n`;
  for (const q of math.controls) md += `| ${q.id} | ${q.target.toFixed(1)} | ${q.abs.toFixed(3)} | ${q.conc.toFixed(4)} | ${q.pctOfTarget.toFixed(2)} % |\n`;
  md += `\nThe hook number (${math.hook.abs.toFixed(3)}) is control ${math.hook.id}; the video answers it as ${math.hook.conc.toFixed(2)} a.u. **No acceptance limit is stated or implied**: the video says limits come from the IFU and the laboratory SOP. "% of target" is arithmetic, not a pass/fail verdict.\n`;
  md += `\n## 4. What the numbers do NOT mean\n\n- R² close to 1 does not prove linearity or accuracy; residuals are shown for that reason (textbook statistics, see epistemic table).\n- Number of calibrators, blank handling and the curve model (linear, spline, 4PL…) are method-specific and come from the reagent IFU (app text \`calGuide2\`).\n- LabGuide itself does not compute calibration curves: it records the lot, the assigned values the user copies from the value sheet, the outcome, QC after calibration and the approver.\n`;
  fs.writeFileSync(path.join(dir, 'MATH_APPENDIX.md'), md);
}

// -------------------------------------------------------------- OUTPUTS
{
  const out = path.join(studio, 'out', id);
  if (fs.existsSync(out)) {
    let md = `# ${storyboard.title.en} — render outputs\n\n<!-- GENERATED by video_studio/scripts/docs.mjs -->\n\n`;
    md += `Files live in \`video_studio/out/${id}/<lang>/\` (gitignored, not uploaded anywhere). Audio: ${voiced ? `English synthetic narration (${timing.voice}); listening review **pending**` : 'none (silent)'}.\n\n`;
    md += `| File | Duration (s) | Size (MB) | Video | Audio | sha256 |\n|---|---|---|---|---|---|\n`;
    for (const lang of LANGS) {
      const d = path.join(out, lang);
      if (!fs.existsSync(d)) continue;
      for (const name of fs.readdirSync(d).sort()) {
        const p = path.join(d, name);
        const sha = createHash('sha256').update(fs.readFileSync(p)).digest('hex');
        let dur = '', v = '', a = '';
        if (name.endsWith('.mp4')) {
          const j = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_streams', '-show_format', '-of', 'json', p]).toString());
          const vs = j.streams.find((s) => s.codec_type === 'video');
          const as = j.streams.find((s) => s.codec_type === 'audio');
          dur = Number(j.format.duration).toFixed(2);
          v = `${vs.codec_name} ${vs.profile} ${vs.width}×${vs.height} ${vs.pix_fmt} ${vs.r_frame_rate}`;
          a = as ? `${as.codec_name} ${as.sample_rate} Hz ${as.channels} ch` : 'none';
        } else if (name.endsWith('.jpg')) {
          const j = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_streams', '-of', 'json', p]).toString());
          v = `${j.streams[0].width}×${j.streams[0].height} JPEG`;
        }
        md += `| \`${lang}/${name}\` | ${dur} | ${(fs.statSync(p).size / 1e6).toFixed(2)} | ${v} | ${a} | \`${sha}\` |\n`;
      }
    }
    fs.writeFileSync(path.join(dir, 'OUTPUTS.md'), md);
  }
}
console.log(`docs: ${path.relative(studio, dir)}/SCRIPT.md, MATH_APPENDIX.md${fs.existsSync(path.join(studio, 'out', id)) ? ', OUTPUTS.md' : ''}`);
