// MATH_APPENDIX.md for the leukocyte differential video. Uses the SAME math
// as the video (src/lib/differential.js, passed in as `math`) and runs the
// independent Python cross-check (scripts/crosscheck_leukocyte.py); if an
// app walk exists, the numbers the APP computed (frames.json → record) are
// compared too.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fmtMax, tallyAt} from '../src/lib/differential.js';

export function leukocyteAppendix({dir, storyboard, math, studio}) {
  const sbPath = path.join(dir, 'storyboard.json');
  const walk = path.join(studio, 'public/frames/en/leukocyte/frames.json');
  const pyArgs = ['-I', path.join(studio, 'scripts/crosscheck_leukocyte.py'), sbPath];
  if (fs.existsSync(walk)) pyArgs.push(walk);
  let py = null;
  let pyErr = null;
  try {
    py = JSON.parse(execFileSync('python3', pyArgs).toString());
  } catch (e) {
    pyErr = String(e.stdout ?? e.message);
  }
  const app = fs.existsSync(walk) ? JSON.parse(fs.readFileSync(walk, 'utf8')) : null;
  const d = storyboard.data;
  let md = `# ${storyboard.title.en} — math appendix\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs (same code as the video: video_studio/src/lib/differential.js) -->\n\n`;
  md += `**Illustrative count — not a patient result.** One invented 100-cell tally (\`storyboard.json → data.sequence\`, the order in which cells are met) and an invented WBC of ${d.wbc} ${d.wbcUnit}. Every number on screen (running tally, class counts, %, absolute counts) is computed from these in code; the real app frames were produced by tapping the same sequence in the app, so the app computed its own numbers from the same taps.\n\n`;
  md += `## 1. Definitions (as in the app, \`differential_controller.dart → DiffRecord\`)\n\n`;
  md += `- percent(c) = count(c) × 100 / total\n- absolute(c) = count(c) / total × WBC (×10⁹/L; only when a WBC is entered)\n- neutrophils (assessment) = segmented + band\n- on screen: up to 1 decimal for %, up to 2 for ×10⁹/L, trailing zeros dropped (the app's \`formatResult(maxDecimals)\`)\n\n`;
  md += `## 2. Result\n\n| Cell | n | % | ×10⁹/L (WBC ${d.wbc}) | shown % | shown ×10⁹/L |\n|---|---|---|---|---|---|\n`;
  for (const r of math.rows) {
    md += `| ${r.cell} | ${r.count} | ${r.percent.toFixed(4)} | ${r.absolute.toFixed(4)} | ${fmtMax(r.percent, 'en', 1)} | ${fmtMax(r.absolute, 'en', 2)} |\n`;
  }
  md += `| **Σ** | **${math.total}** | ${math.pctSum.toFixed(4)} | ${math.absSum.toFixed(4)} | ${fmtMax(math.pctSum, 'en', 1)} | ${fmtMax(math.absSum, 'en', 2)} |\n`;
  md += `\nNeutrophils (segmented + band): ${math.counts.segmented + math.counts.band} % · ${math.neutrophilsAbs.toFixed(4)} ×10⁹/L (shown ${fmtMax(math.neutrophilsAbs, 'en', 2)}).\n`;
  md += `\n## 3. Running tally (what the counting scenes show)\n\n| After n cells | Segs | Bands | Lymph | Mono | Eos | Baso |\n|---|---|---|---|---|---|---|\n`;
  for (const n of [1, 2, 3, 4, 5, 6, d.midAt, d.midAt + 1, d.hook.a, d.target]) {
    const t = tallyAt(math.sequence, n);
    md += `| ${n} | ${t.segmented} | ${t.band} | ${t.lymphocyte} | ${t.monocyte} | ${t.eosinophil} | ${t.basophil} |\n`;
  }
  md += `\nFirst ${d.firstTaps} taps (one app frame each): ${math.sequence.slice(0, d.firstTaps).join(', ')}. Cell ${d.midAt + 1} (tapped in Microscope mode): ${math.sequence[d.midAt]}.\n`;
  md += `\nHook: the paper tally fills to ${d.hook.a} cells (counts = first ${d.hook.a} of the sequence), then a second sum "${d.hook.b}?" appears — the point is a lost row of ten; no result is derived from it.\n`;
  md += `\n## 4. Independent Python cross-check\n\n`;
  if (py) {
    md += `\`python3 -I video_studio/scripts/crosscheck_leukocyte.py docs/video/leukocyte/storyboard.json${app ? ' video_studio/public/frames/en/leukocyte/frames.json' : ''}\` (exact fractions, no shared code):\n\n`;
    md += `| Cell | n | % | ×10⁹/L | JS = Python |\n|---|---|---|---|---|\n`;
    for (const r of math.rows) {
      const p = py.rows[r.cell];
      const ok = p.count === r.count && Math.abs(p.percent - r.percent) < 1e-9 && Math.abs(p.absolute - r.absolute) < 1e-9;
      md += `| ${r.cell} | ${p.count} | ${p.percent} | ${p.absolute_2dp} | ${ok ? 'yes' : '**NO**'} |\n`;
    }
    md += `\nΣ % = ${py.percent_sum}, Σ absolute = ${py.absolute_sum}, neutrophils total = ${py.neutrophils_total_abs}; declared counts match the sequence: ${py.declared_counts_match ? 'yes' : '**NO**'}`;
    md += app ? `; numbers computed by the app itself in the walk (frames.json → record) match: ${py.app_match ? 'yes' : '**NO**'}.\n` : `.\n`;
  } else {
    md += `Python cross-check FAILED: ${pyErr}\n`;
  }
  if (app?.copied) {
    md += `\n## 5. The app's own "Copy" text (EN walk, captured from the clipboard channel)\n\n\`\`\`\n${app.copied}\n\`\`\`\n`;
  }
  md += `\n## 6. What the numbers do NOT mean\n\n- The tally is invented for teaching; it is not a patient result and is not presented as typical or normal.\n- No reference interval is stated by the video. The app compares a COMPLETE count with the ranges on the laboratory's report form (editable in "Report reference ranges"; defaults are the app's sourced adult values) and says "This is not a diagnosis".\n- 100 vs 200 cells, and how bands are reported, follow the laboratory SOP (app technique text).\n`;
  return md;
}
