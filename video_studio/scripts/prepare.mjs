#!/usr/bin/env node
// Copies the repository's own assets into the studio (nothing downloaded):
//   assets/fonts/*.ttf                      -> public/fonts/
//   assets/images/logo_mark_large.png       -> public/brand/  (owner's logo, via git if not checked out)
//   tool/illustrations/schematic/<key>.svg  -> src/generated/schematics.js (inline SVG + parsed callout anchors)
// Outputs are gitignored and regenerated on every render.
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const studio = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(studio, '..');

function ensureDir(d) {
  fs.mkdirSync(d, {recursive: true});
}

// Fonts (OFL, see assets/fonts/*-OFL.txt).
const fontsOut = path.join(studio, 'public/fonts');
ensureDir(fontsOut);
for (const f of [
  'Inter-400.ttf',
  'Inter-500.ttf',
  'Inter-600.ttf',
  'Inter-700.ttf',
  'Inter-OFL.txt',
  'InstrumentSerif-Regular.ttf',
  'InstrumentSerif-OFL.txt',
]) {
  fs.copyFileSync(path.join(repo, 'assets/fonts', f), path.join(fontsOut, f));
}

// Owner's logo mark (app icon). Read from the work tree, else from git HEAD.
const brandOut = path.join(studio, 'public/brand');
ensureDir(brandOut);
const logoRel = 'assets/images/logo_mark_large.png';
const logoAbs = path.join(repo, logoRel);
const logoDst = path.join(brandOut, 'logo_mark.png');
if (fs.existsSync(logoAbs)) {
  fs.copyFileSync(logoAbs, logoDst);
} else {
  const buf = execFileSync('git', ['-C', repo, 'show', `HEAD:${logoRel}`], {
    maxBuffer: 32 << 20,
  });
  fs.writeFileSync(logoDst, buf);
}

// Schematics: the app's ORIGINAL apparatus art (docs/SCHEMATICS_PROVENANCE.md).
const keys = ['chemistry', 'photometer', 'mass_spec_gc', 'real_time_pcr', 'osmometer'];
const out = {};
for (const key of keys) {
  const file = path.join(repo, 'tool/illustrations/schematic', `${key}.svg`);
  let svg = fs.readFileSync(file, 'utf8');
  // Parse numbered callouts: <g class="callout" data-n="N"> ... small ellipse
  // (rx 6.5) = target point, big ellipse (rx 28) = badge.
  const callouts = {};
  const re = /<g class="callout" data-n="(\d+)">([\s\S]*?)<\/g>/g;
  let m;
  while ((m = re.exec(svg))) {
    const n = m[1];
    const body = m[2];
    const ells = [...body.matchAll(/<ellipse cx="([\d.]+)" cy="([\d.]+)" rx="([\d.]+)"/g)].map(
      (e) => ({x: +e[1], y: +e[2], r: +e[3]}),
    );
    const badge = ells.find((e) => e.r >= 20);
    const target = ells.find((e) => e.r < 20);
    callouts[n] = {
      badge: badge ? [badge.x, badge.y] : null,
      target: target ? [target.x, target.y] : badge ? [badge.x, badge.y] : null,
    };
  }
  // Make ids unique per schematic so two inline SVGs never clash.
  svg = svg
    .replace(/id="([^"]+)"/g, `id="${key}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${key}-$1)`)
    .replace(/<svg /, `<svg class="lg-schematic lg-${key}" `)
    .replace(/ width="1200" height="800"/, ' width="100%" height="100%"');
  const vb = /viewBox="([\d.\s-]+)"/.exec(svg)[1].split(/\s+/).map(Number);
  out[key] = {svg, callouts, viewBox: vb, source: `tool/illustrations/schematic/${key}.svg`};
}
const genDir = path.join(studio, 'src/generated');
ensureDir(genDir);
fs.writeFileSync(
  path.join(genDir, 'schematics.js'),
  '// GENERATED by scripts/prepare.mjs from tool/illustrations/schematic/*.svg — do not edit.\n' +
    `export const schematics = ${JSON.stringify(out)};\n`,
);
console.log(
  `prepare: fonts -> public/fonts, logo -> public/brand, schematics [${keys.join(', ')}] -> src/generated/schematics.js`,
);
for (const k of keys) console.log(`  ${k} callouts:`, JSON.stringify(out[k].callouts));
