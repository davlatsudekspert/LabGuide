// MATH_APPENDIX.md for the calculators overview video: the app computes every
// result on screen; this appendix repeats the arithmetic (JS + independent
// Python) for the illustrative inputs typed by the walk.
import {execFileSync} from 'node:child_process';
import path from 'node:path';

export function appendix({dir, storyboard, math, studio}) {
  const d = storyboard.data;
  let py;
  try {
    py = JSON.parse(execFileSync('python3', ['-I', path.join(studio, 'scripts/crosscheck_calculators.py'), path.join(dir, 'storyboard.json')]).toString());
  } catch (e) {
    py = {error: String(e.message)};
  }
  const dl = d.dilution;
  const u = d.unitCheck;
  let md = `# ${storyboard.title.en} — math appendix\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs -->\n\n`;
  md += `**Illustrative inputs — not a patient.** Every result in the video is computed **by the app** on the filmed screens (\`flutter_walk/calculators_walk_test.dart\`). This appendix repeats the arithmetic only as a check. The hook shows the app's formula text with "= ?" and no result.\n\n`;
  md += `| Screen | Inputs | App on screen | JS (video lib) | Python (independent) |\n|---|---|---|---|---|\n`;
  md += `| eGFR · CKD-EPI 2021 (\`e_result\`) | creatinine ${d.egfr.creatinine} µmol/L, age ${d.egfr.age}, ${d.egfr.sex} | 95 mL/min/1.73 m², KDIGO G1 | ${math.egfrValue.toFixed(2)} (÷ 88.4) | ${py.egfr ?? '—'} (molar mass 113.12 g/mol), ${py.kdigo_category ?? '—'} |\n`;
  md += `| eGFR, age ${d.egfr.childAge} (\`e_child\`) | same, age ${d.egfr.childAge} | refused (under 18) | — | — |\n`;
  md += `| Dilution (\`d_result\`) | C₁ ${dl.c1}, C₂ ${dl.c2}, V₂ ${dl.v2} mL | V₁ = 20 mL | ${(dl.c2 * dl.v2) / dl.c1} | ${py.dilution_v1 ?? '—'} |\n`;
  md += `| Calculated osmolality (\`o_unit\`) | Na ${u.sodium}, glucose ${u.glucose} "mmol/L", urea ${u.urea} | 375 mOsm/kg + unit check on glucose | ${2 * u.sodium + u.glucose + u.urea} | ${py.osmo_unitcheck_calculated ?? '—'} |\n\n`;
  md += `CKD-EPI 2021 (as in \`lib/features/tools/calc_info.dart\`): eGFR = 142 × min(Scr/κ, 1)^α × max(Scr/κ, 1)^−1.200 × 0.9938^age × 1.012 [if female]; female κ = 0.7, α = −0.241; male κ = 0.9, α = −0.302; Scr in mg/dL.\n\n`;
  md += `## What the numbers do NOT mean\n\n- No patient, no interpretation of "G1", no reference interval. The glucose-90 example exists only to show the app's unit check.\n`;
  return md;
}
