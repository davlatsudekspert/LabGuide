// MATH_APPENDIX.md for the osmometry video (same math as the video:
// src/lib/osmometry.js) + the independent Python check.
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {calcCheck} from '../src/lib/osmometry.js';

export function appendix({dir, storyboard, math, studio}) {
  const d = storyboard.data;
  const p = d.curve;
  let py;
  try {
    py = JSON.parse(execFileSync('python3', ['-I', path.join(studio, 'scripts/crosscheck_osmometry.py'), path.join(dir, 'storyboard.json')]).toString());
  } catch (e) {
    py = {error: String(e.message)};
  }
  const js = calcCheck(d.calc);
  let md = `# ${storyboard.title.en} — math appendix\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs (same code as the video: video_studio/src/lib/osmometry.js) -->\n\n`;
  md += `**Illustrative freezing curves — not a real instrument, sample or result.** Temperature in arbitrary units, pure water's freezing point at 0. **No number is drawn on the axes** (lesson 24).\n\n`;
  md += `## 1. Model\n\n`;
  md += `- Cooling (Newton): T(t) = Tb + (T0 − Tb)·e^(−t/τ), T0 = ${p.t0}, Tb = ${p.tb}, τ = ${p.tau}.\n`;
  md += `- Seeding at the supercooled minimum Tsup: ts = −τ·ln((Tsup − Tb)/(T0 − Tb)).\n`;
  md += `- After seeding: T(t) = Tf − (Tf − Tsup)·e^(−(t − ts)/τr) − k·max(0, t − ts − plateau)², τr = ${p.tauR}, plateau = ${p.plateau}, k = ${p.k}.\n`;
  md += `- Depression ΔT = T(water) − Tf. The shapes follow the app's principle text (supercooling → stirring wire starts freezing → latent heat → plateau). No cryoscopic constant is used or shown.\n\n`;
  md += `## 2. Samples\n\n| Sample | Tsup | Tf (plateau) | seed time ts (JS) | ts (Python bisection) | T 2 s after seeding (Python) | ΔT (JS) | ΔT (Python) |\n|---|---|---|---|---|---|---|---|\n`;
  for (const s of math.samples) {
    const q = py.samples?.[s.id] ?? {};
    md += `| ${s.id} | ${s.tsup} | ${s.tf} | ${s.ts.toFixed(6)} | ${q.seed_time ?? '—'} | ${q.plateau_temp_2s_after_seed ?? '—'} | ${s.depression.toFixed(6)} | ${q.depression ?? '—'} |\n`;
  }
  md += `\nDeeper depression (more dissolved particles in the video's story): sample **${py.deeper ?? '—'}** — the hook's "lower plateau".\n\n`;
  md += `## 3. Calculator (filmed from the app)\n\n`;
  md += `Illustrative inputs typed into the app's own calculator by the walk (\`flutter_walk/osmometry_walk_test.dart\`): Na ${d.calc.sodium} mmol/L, glucose ${d.calc.glucose} mmol/L, urea ${d.calc.urea} mmol/L, measured ${d.calc.measured} mOsm/kg.\n\n`;
  md += `| | App on screen | JS (this appendix) | Python |\n|---|---|---|---|\n`;
  md += `| Calculated osmolality = 2·Na + glucose + urea | 290 mOsm/kg | ${js.calculated} | ${py.calc?.calculated ?? '—'} |\n`;
  md += `| Osmolal gap = measured − calculated | 10 mOsm/kg | ${js.gap} | ${py.calc?.gap ?? '—'} |\n\n`;
  md += `Formula and gap definition as in \`lib/features/tools/clinical_calculators.dart\` (\`calculatedOsmolality\`; the app cites Lynd 2008 Table 1 for the mmol/L form, Rasouli 2016 for the mg/dL form).\n\n`;
  md += `## 4. What the numbers do NOT mean\n\n- No reference interval, no "normal" gap, no diagnosis (the app's own note: it does not diagnose).\n- No real temperatures; the plateau heights only show "lower vs higher".\n`;
  return md;
}
