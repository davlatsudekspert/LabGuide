// MATH_APPENDIX.md for the real-time PCR video (same math as the video:
// src/lib/qpcr.js) + the independent Python bisection check.
import {execFileSync} from 'node:child_process';
import path from 'node:path';

export function appendix({dir, storyboard, math, studio}) {
  const d = storyboard.data;
  let py;
  try {
    py = JSON.parse(execFileSync('python3', ['-I', path.join(studio, 'scripts/crosscheck_qpcr.py'), path.join(dir, 'storyboard.json')]).toString());
  } catch (e) {
    py = {error: String(e.message)};
  }
  let md = `# ${storyboard.title.en} — math appendix\n\n`;
  md += `<!-- GENERATED by video_studio/scripts/docs.mjs (same code as the video: video_studio/src/lib/qpcr.js) -->\n\n`;
  md += `**Illustrative curves — not a real assay, instrument, threshold setting or patient result.** Fluorescence in arbitrary units.\n\n`;
  md += `## 1. Model\n\n- F(c) = base + top / (1 + e^(−(c − mid)/slope)), base = ${d.base}; NTC: base + drift·c.\n- Threshold T = ${d.threshold} (illustrative). Cq solved exactly: c = mid − slope · ln(top / (T − base) − 1).\n- App card wording (SOURCED, NCBI Bookshelf PCR page): "the key readout is the quantification cycle (Cq) at which fluorescence crosses a threshold; a lower Cq means more starting target"; "roughly doubling the target each cycle".\n\n`;
  md += `## 2. Samples\n\n| Sample | mid | slope | top | Cq (JS) | Cq (Python bisection) | shown | in the hook line |\n|---|---|---|---|---|---|---|---|\n`;
  for (const s of math.samples) {
    const p = py.cq?.[s.id];
    md += `| ${s.id} | ${s.mid ?? '—'} | ${s.slope ?? '—'} | ${s.top ?? '—'} | ${s.cq == null ? 'none (no crossing)' : s.cq.toFixed(6)} | ${p == null ? 'none' : p} | ${s.cq == null ? '—' : s.cq.toFixed(1)} | ${s.cq == null ? '—' : s.cq.toFixed(0)} |\n`;
  }
  md += `\nNTC signal at cycle ${d.cycles}: ${py.ntc_max_signal ?? '—'} (stays below the threshold — "no amplification"; the video adds that this alone does not prove a negative, as the app card says).\n`;
  md += `\n## 3. Doubling bars\n\n${math.doubling.map((x) => `cycle ${x.n}: ${x.copies}`).join(' · ')} (Python: ${(py.doubling ?? []).join(', ')}). Idealised 2^n for "roughly doubles"; real efficiency is assay-specific and **not** stated.\n`;
  md += `\n## 4. What the numbers do NOT mean\n\n- No fold-difference between A and B is claimed (it would require an efficiency assumption).\n- No threshold-setting rule, no assay cut-off, no clinical interpretation.\n`;
  return md;
}
